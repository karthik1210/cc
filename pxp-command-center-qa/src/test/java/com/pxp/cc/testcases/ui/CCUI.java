	//////// Methods : Support Data Initilizer - If we need some data load at the
	//////// starting of test
	public void initializeTestData() throws Exception {
		///// Below Data Used for Test PrivacyPoliciesSettingsTest
		if (autoGeneratedClientName == null) {
			autoGeneratedClientName = testData.getProperty("new.client.name2")
					.concat(CCUtils.generateRandomStringWithoutSymbolsOrNumbers(25).toLowerCase());
		}

		if (clientSap == null) {
			clientSap = testData.getProperty("new.client.sap")
					.concat(CCUtils.generateAlphaNumericStringIncludingSpecialChar(20));
		}
		if (clientType == null) {
			clientType = testData.getProperty("new.client.type");
		}
		if (timeZone == null) {
			timeZone = testData.getProperty("new.client.timezone");
			;
		}
		if (systemOrEnterprise == null) {
			systemOrEnterprise = testData.getProperty("new.system");
			;
		}
		if (timeZoneDisplayName == null) {
			timeZoneDisplayName = testData.getProperty("new.timezone.display.name");
			;
		}
		if (solution == null) {
			solution = testData.getProperty("solution.forms");
			;
		}
	}

