    public static void getClientSystementErpriseandPractice() throws Exception {

        if (clientSystementErpriseandPractice == null) {
            clientSystementErpriseandPractice = new HashMap<String, String>();

            String clientNam = getNGHierarchyClientCreation().createNewActiveClient(autoGeneratedClientName, clientSap, clientType, timeZone);
            String systemName = getNGHierarchyClientCreation().createNewActiveSystem(systemOrEnterprise, systemOrEnterprise);
            String enterpriseName = getNGHierarchyClientCreation().createNewActiveEnterprise(systemOrEnterprise, systemOrEnterprise, timeZoneDisplayName);
            String practiceName = getNGHierarchyClientCreation().createNewActivePractice(systemOrEnterprise, systemOrEnterprise, timeZoneDisplayName, solution);

            clientSystementErpriseandPractice.put("clientNam", clientNam);
            clientSystementErpriseandPractice.put("systemName", systemName);
            clientSystementErpriseandPractice.put("enterpriseName", enterpriseName);
            clientSystementErpriseandPractice.put("practiceName", practiceName);

        } else {
            ccui = new CCUI(testData, driver);
            ccui.getNgHierarchyClientCreationPage().searchNode(clientSystementErpriseandPractice.get("clientNam"));
            ccui.getNgHierarchyClientCreationPage().clickSearchButton();
            ccui.getNgHierarchyClientCreationPage().clickSearchResult(clientSystementErpriseandPractice.get("clientNam"));
            ccui.getGeneralSettingsPage().verifyClientNodeIsSelected();
            ccui.getPrivacyPolicySettingsPage().clickOnSystemArrow(clientSystementErpriseandPractice.get("systemName"));
            ccui.getPrivacyPolicySettingsPage().clickOnEnterpriseArrow(clientSystementErpriseandPractice.get("enterpriseName"));
            ccui.getPrivacyPolicySettingsPage().clickOnPracticeLevel(clientSystementErpriseandPractice.get("practiceName"));
        }
    }

